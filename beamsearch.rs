// ============================================================
// Heuristic Search Library
// ============================================================
//
// このファイルは AHC 用の「1ファイル完結」ライブラリ。
// 外部 crate / mod に依存せず、そのまま提出ファイルに貼り付けて使う。
//
// 基本方針:
//
//   Problem
//      ↓
//   State を作る
//      ↓
//   Action を列挙する
//      ↓
//   Action を適用して次の State を作る
//      ↓
//   State を評価する
//      ↓
//   Beam Search
//
// BeamSearch::new(1) とすれば貪欲法としても使える。
//
// ------------------------------------------------------------
// 今後拡張したい機能の候補:
//
// - 時間制限
// - ランダム探索
// - 重複状態除去
// - 候補生成数の制限
// - 評価関数と最終スコアの分離
// - 差分評価
// - 焼きなまし法
//
// ============================================================

// ============================================================
// Problem trait
// ============================================================

pub trait Problem {
    // --------------------------------------------------------
    // 問題ごとに定義する型
    // --------------------------------------------------------
    //
    // State:
    //   探索中に保持する「状態」。
    //
    //   例:
    //     - 現在何日目か
    //     - 各頂点の状態
    //     - 現在の盤面
    //     - 現在の解
    //
    // Action:
    //   1回の遷移で行う操作。
    //
    //   例:
    //     - その日に選ぶコンテスト
    //     - 頂点を1つ選ぶ
    //     - ある要素を交換する
    //     - 次に配置するもの
    type State: Clone;
    type Action: Clone;

    // --------------------------------------------------------
    // 初期状態
    // --------------------------------------------------------
    //
    // 探索開始時の状態を返す。
    //
    // ここでは「解そのもの」を作る必要はない。
    // 探索開始時点の情報だけ入った State を返せばよい。
    //
    // 例:
    //
    // fn initial_state(&self) -> Self::State {
    //     State {
    //         day: 0,
    //         score: 0,
    //         ...
    //     }
    // }
    fn initial_state(&self) -> Self::State;

    // --------------------------------------------------------
    // 現在の状態から可能な Action を列挙する
    // --------------------------------------------------------
    //
    // state を見て、「ここから選べる手」を返す。
    //
    // 例えば:
    //
    // fn actions(&self, state: &Self::State) -> Vec<Self::Action> {
    //     if state.day >= self.d {
    //         return vec![];
    //     }
    //
    //     (0..26).collect()
    // }
    //
    // 注意:
    //   ここが重いとビームサーチ全体も遅くなる。
    //   必要なら Vec ではなく、後で iterator ベースに拡張してもよい。
    fn actions(&self, state: &Self::State) -> Vec<Self::Action>;

    // --------------------------------------------------------
    // State に Action を適用して次の State を作る
    // --------------------------------------------------------
    //
    // 基本的には State を clone して書き換える。
    //
    // 小さい State ならこれでよい。
    //
    // State が非常に大きくなったら、
    //   - 差分更新
    //   - undo/rollback
    //   - Copy を避ける
    // などを検討する。
    //
    // 例:
    //
    // fn apply(
    //     &self,
    //     state: &Self::State,
    //     action: &Self::Action,
    // ) -> Self::State {
    //     let mut next = state.clone();
    //
    //     // next を action に応じて更新
    //
    //     next
    // }
    fn apply(&self, state: &Self::State, action: &Self::Action) -> Self::State;

    // --------------------------------------------------------
    // 状態の評価値
    // --------------------------------------------------------
    //
    // 「この状態はどれくらい良いか」を返す。
    //
    // 基本方針:
    //   値が大きいほど良い。
    //
    // ビームサーチでは、この値の大きい状態を残す。
    //
    // 例:
    //
    // fn evaluate(&self, state: &Self::State) -> i64 {
    //     state.score
    // }
    //
    // --------------------------------------------------------
    // 重要:
    // ここで使う値は「最終的な公式得点」と完全に一致しなくてもよい。
    //
    // 例えば:
    //
    //   現在のスコア
    //   + 将来の期待値
    //
    // のような「探索用評価関数」にすることもできる。
    fn evaluate(&self, state: &Self::State) -> i64;

    // --------------------------------------------------------
    // 終端状態かどうか
    // --------------------------------------------------------
    //
    // 「これ以上 Action を選ぶ必要がない状態」なら true。
    //
    // 例:
    //
    // fn is_terminal(&self, state: &Self::State) -> bool {
    //     state.day == self.d
    // }
    fn is_terminal(&self, state: &Self::State) -> bool;

    // --------------------------------------------------------
    // 答えを出力
    // --------------------------------------------------------
    //
    // 探索によって得られた Action 列を、
    // 問題の要求する出力形式で標準出力に出力する。
    //
    // AHCでは問題ごとに出力形式が異なるため、
    // ここだけ問題側で実装する。
    //
    // 例えば Intro Heuristics A なら:
    //
    // fn output(&self, actions: &[Self::Action]) {
    //     for &contest in actions {
    //         println!("{}", contest + 1);
    //     }
    // }
    //
    // 探索結果そのものは Vec<Action> として渡される。
    // 答えの復元はライブラリ側で行うため、
    // 問題側で State から答えを復元する必要はない。
    fn output(&self, actions: &[Self::Action]);
}

// ============================================================
// Beam Search
// ============================================================
//
// Beam Search の探索木を表現するための構造体。
//
// State:
//   現在の状態そのもの。
//
// score:
//   現在の状態の評価値。
//   大きいほど良い状態とする。
//
// path:
//   答え復元用の PathNode へのインデックス。
//
// ============================================================

#[derive(Clone)]
struct PathNode<A> {
    // 1手前の PathNode。
    //
    // None の場合、この Action が最初の1手。
    parent: Option<usize>,

    // 親からこの状態へ遷移するときに選んだ Action。
    action: A,
}

struct BeamNode<S> {
    // 現在の状態。
    state: S,

    // 現在の状態の評価値。
    score: i64,

    // 答え復元用 PathNode のインデックス。
    path: Option<usize>,
}

// ------------------------------------------------------------
// 次の Beam の候補。
// ------------------------------------------------------------
//
// 現在の Beam に含まれる全 State を展開した結果、一時的に作る。
// この中から評価値の高いものだけを次の Beam に残す。
// ------------------------------------------------------------

struct Candidate<S, A> {
    state: S,
    score: i64,

    // この候補の親にあたる PathNode。
    parent_path: Option<usize>,

    // 親からこの候補へ遷移するときに選んだ Action。
    action: A,
}

// ============================================================
// BeamSearch
// ============================================================

pub struct BeamSearch {
    // 各深さで残す State の数。
    //
    // width = 1 なら貪欲法になる。
    width: usize,
}

impl BeamSearch {
    // --------------------------------------------------------
    // Beam width を指定する。
    // --------------------------------------------------------
    //
    // 例:
    //
    // BeamSearch::new(1)
    //     → 貪欲法
    //
    // BeamSearch::new(100)
    //     → 各深さで上位100状態
    //
    // BeamSearch::new(1000)
    //     → 各深さで上位1000状態
    //
    // --------------------------------------------------------

    pub fn new(width: usize) -> Self {
        assert!(width >= 1);

        Self { width }
    }

    // --------------------------------------------------------
    // Beam Search を実行して出力する。
    // --------------------------------------------------------
    //
    // 探索結果を Vec<Action> として返すのではなく、
    // Problem::output() に渡して問題側で出力する。
    //
    // そのため AHC の main は、
    //
    //     BeamSearch::new(1000).solve(&problem);
    //
    // だけでよい。
    // --------------------------------------------------------

    pub fn solve<P>(&self, problem: &P)
    where
        P: Problem,
    {
        let answer = self.search(problem);

        problem.output(&answer);
    }

    // --------------------------------------------------------
    // 実際の Beam Search。
    // --------------------------------------------------------
    //
    // solve() と探索処理を分離している。
    //
    // solve():
    //     探索 + 出力
    //
    // search():
    //     探索のみ
    //
    // としておくことで、将来的にテストなどで
    // 探索結果だけ欲しくなった場合にも対応しやすい。
    // --------------------------------------------------------

    fn search<P>(&self, problem: &P) -> Vec<P::Action>
    where
        P: Problem,
    {
        // ----------------------------------------------------
        // 初期状態を作る。
        // ----------------------------------------------------

        let initial_state = problem.initial_state();

        let initial = BeamNode {
            score: problem.evaluate(&initial_state),
            state: initial_state,
            path: None,
        };

        // 現在の Beam。
        //
        // 最初は初期状態1個だけ。
        let mut current = vec![initial];

        // ----------------------------------------------------
        // 答え復元用のノード。
        // ----------------------------------------------------
        //
        // State の中に Vec<Action> を持たせる代わりに、
        //
        //     parent + action
        //
        // だけを保存する。
        //
        // 例えば、
        //
        //     Action A
        //       ↓
        //     Action B
        //       ↓
        //     Action C
        //
        // なら、
        //
        //     #0: parent=None, action=A
        //     #1: parent=0,    action=B
        //     #2: parent=1,    action=C
        //
        // となる。
        // ----------------------------------------------------

        let mut path_nodes: Vec<PathNode<P::Action>> = Vec::new();

        // ====================================================
        // 深さごとの探索
        // ====================================================

        loop {
            // ------------------------------------------------
            // 現在の Beam がすべて終端なら終了。
            // ------------------------------------------------

            if current.iter().all(|node| problem.is_terminal(&node.state)) {
                break;
            }

            // ------------------------------------------------
            // 現在の Beam を1段階展開する。
            // ------------------------------------------------
            //
            // 例えば、
            //
            //     Beam width = 100
            //     1状態あたり Action が26個
            //
            // なら、
            //
            //     100 × 26 = 2600候補
            //
            // を作る。
            // ------------------------------------------------

            let mut candidates = Vec::new();

            for node in &current {
                // --------------------------------------------
                // すでに終端状態なら展開しない。
                // --------------------------------------------

                if problem.is_terminal(&node.state) {
                    continue;
                }

                // --------------------------------------------
                // この State から可能な Action を取得。
                // --------------------------------------------

                let actions = problem.actions(&node.state);

                // --------------------------------------------
                // 全 Action を適用して候補を作る。
                // --------------------------------------------

                for action in actions {
                    let next_state = problem.apply(&node.state, &action);

                    let score = problem.evaluate(&next_state);

                    candidates.push(Candidate {
                        state: next_state,
                        score,
                        parent_path: node.path,
                        action,
                    });
                }
            }

            // ------------------------------------------------
            // 候補が1つもない場合。
            // ------------------------------------------------
            //
            // 通常は is_terminal() と actions() の実装が
            // 正しければ起こらない。
            //
            // 念のため探索を終了する。
            // ------------------------------------------------

            if candidates.is_empty() {
                break;
            }

            // ------------------------------------------------
            // 評価値の高い順に並べる。
            // ------------------------------------------------
            //
            // 大きいほど良い。
            // ------------------------------------------------

            candidates.sort_unstable_by(|a, b| b.score.cmp(&a.score));

            // ------------------------------------------------
            // 上位 width 個だけ残す。
            // ------------------------------------------------
            //
            // ここが Beam Search の核心。
            // ------------------------------------------------

            candidates.truncate(self.width);

            // ------------------------------------------------
            // 次の Beam を作る。
            // ------------------------------------------------

            let mut next = Vec::with_capacity(candidates.len());

            for candidate in candidates {
                // --------------------------------------------
                // この候補を採用したので、
                // 答え復元用の PathNode を作る。
                // --------------------------------------------

                let path_id = path_nodes.len();

                path_nodes.push(PathNode {
                    parent: candidate.parent_path,
                    action: candidate.action,
                });

                // --------------------------------------------
                // 次の Beam に追加。
                // --------------------------------------------

                next.push(BeamNode {
                    state: candidate.state,
                    score: candidate.score,
                    path: Some(path_id),
                });
            }

            // ------------------------------------------------
            // 次の深さへ。
            // ------------------------------------------------

            current = next;
        }

        // ====================================================
        // 最終状態を選ぶ
        // ====================================================
        //
        // 最後の Beam の中で評価値が最大の State を採用。
        // ====================================================

        let best = current
            .iter()
            .max_by(|a, b| a.score.partial_cmp(&b.score).unwrap_or(Ordering::Equal))
            .expect("beam search produced no state");

        // ====================================================
        // Action 列を復元
        // ====================================================

        self.restore_path(best.path, &path_nodes)
    }

    // --------------------------------------------------------
    // PathNode を逆向きに辿って Action 列を復元する。
    // --------------------------------------------------------

    fn restore_path<A: Clone>(
        &self,
        mut path: Option<usize>,
        path_nodes: &[PathNode<A>],
    ) -> Vec<A> {
        let mut answer = Vec::new();

        // ----------------------------------------------------
        // 最終状態から初期状態へ向かって辿る。
        // ----------------------------------------------------

        while let Some(id) = path {
            let node = &path_nodes[id];

            answer.push(node.action.clone());

            path = node.parent;
        }

        // ----------------------------------------------------
        // 後ろから辿っているので逆順にする。
        // ----------------------------------------------------

        answer.reverse();

        answer
    }
}

// ============================================================
// Greedy
// ============================================================
//
// 貪欲法 = Beam width 1
//
// つまり独自の探索処理は実装せず、
// BeamSearch をそのまま利用する。
// ============================================================

pub struct Greedy;

impl Greedy {
    // --------------------------------------------------------
    // 貪欲法を実行して出力する。
    // --------------------------------------------------------

    pub fn solve<P>(&self, problem: &P)
    where
        P: Problem,
    {
        BeamSearch::new(1).solve(problem);
    }
}

